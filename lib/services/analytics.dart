import '../core/constants/enums.dart';
import '../domain/models/incident.dart';

class DeptWorkload {
  const DeptWorkload(this.open, this.resolved);
  final int open, resolved;
}

class AnalyticsReport {
  const AnalyticsReport({
    required this.total,
    required this.open,
    required this.resolved,
    required this.closedOther,
    required this.openByPriority,
    required this.byCategory,
    required this.byDepartment,
    required this.dailyCreated,
    required this.overdueOpen,
    required this.needsReview,
    required this.avgResolutionDays,
  });

  final int total, open, resolved, closedOther;
  final Map<Priority, int> openByPriority;
  final Map<IncidentCategory, int> byCategory;
  final Map<String, DeptWorkload> byDepartment;

  /// Reports created per day, oldest first, ending today. Length = [Analytics.trendDays].
  final List<int> dailyCreated;
  final int overdueOpen;
  final int needsReview;

  /// Mean of (last update - created) for resolved reports. This is approximate
  /// because "last update" can also change on an officer override. Null when
  /// nothing has been resolved.
  final double? avgResolutionDays;

  /// Plain-language findings from fixed rules. Not generated by a model.
  List<String> get summary => Analytics._summarize(this);
}

class Analytics {
  static const trendDays = 14;
  static const overdueAfter = Duration(days: 7);

  static AnalyticsReport compute(Iterable<Incident> incidents, {required DateTime now}) {
    final list = incidents.toList();
    final open = list.where((i) => i.status.isOpen).toList();
    final resolved = list.where((i) => i.status == IncidentStatus.resolved).toList();

    final openByPriority = {
      for (final p in Priority.values) p: open.where((i) => i.priority == p).length,
    };

    final byCategory = <IncidentCategory, int>{};
    for (final i in list) {
      byCategory[i.category] = (byCategory[i.category] ?? 0) + 1;
    }

    final byDept = <String, DeptWorkload>{};
    for (final d in list.map((i) => i.departmentId).toSet()) {
      final inDept = list.where((i) => i.departmentId == d);
      byDept[d] = DeptWorkload(
        inDept.where((i) => i.status.isOpen).length,
        inDept.where((i) => i.status == IncidentStatus.resolved).length,
      );
    }

    final today = DateTime(now.year, now.month, now.day);
    final daily = List<int>.filled(trendDays, 0);
    for (final i in list) {
      final day = DateTime(i.createdAt.year, i.createdAt.month, i.createdAt.day);
      final ago = today.difference(day).inDays;
      if (ago >= 0 && ago < trendDays) daily[trendDays - 1 - ago]++;
    }

    final overdue = open.where((i) => now.difference(i.createdAt) >= overdueAfter).length;
    final review = open.where((i) => i.needsHumanReview).length;

    double? avg;
    if (resolved.isNotEmpty) {
      final totalDays = resolved
          .map((i) => i.updatedAt.difference(i.createdAt).inMinutes / (60 * 24))
          .reduce((a, b) => a + b);
      avg = totalDays / resolved.length;
    }

    return AnalyticsReport(
      total: list.length,
      open: open.length,
      resolved: resolved.length,
      closedOther: list.length - open.length - resolved.length,
      openByPriority: openByPriority,
      byCategory: byCategory,
      byDepartment: byDept,
      dailyCreated: daily,
      overdueOpen: overdue,
      needsReview: review,
      avgResolutionDays: avg,
    );
  }

  static List<String> _summarize(AnalyticsReport r) {
    if (r.total == 0) return ['No reports yet, so there is nothing to summarise.'];
    final out = <String>[];

    final urgent = (r.openByPriority[Priority.critical] ?? 0) +
        (r.openByPriority[Priority.high] ?? 0);
    out.add(r.open == 0
        ? 'All ${r.total} reports are closed.'
        : '${r.open} of ${r.total} reports are open; $urgent of them are High or Critical.');

    if (r.byCategory.isNotEmpty) {
      final top = r.byCategory.entries.reduce((a, b) => a.value >= b.value ? a : b);
      out.add('Most common category: ${top.key.label} (${top.value} of ${r.total}).');
    }

    final recent = r.dailyCreated.sublist(Analytics.trendDays - 7).fold<int>(0, (a, b) => a + b);
    final earlier = r.dailyCreated.sublist(0, 7).fold<int>(0, (a, b) => a + b);
    if (recent + earlier > 0) {
      final trend = recent > earlier
          ? 'up from $earlier'
          : recent < earlier
              ? 'down from $earlier'
              : 'the same as';
      out.add('$recent new reports in the last 7 days, '
          '${recent == earlier ? '$trend the 7 days before' : '$trend in the 7 days before'}.');
    }

    if (r.overdueOpen > 0) {
      out.add('${r.overdueOpen} open report${r.overdueOpen == 1 ? ' has' : 's have'} '
          'been waiting 7 days or more.');
    }
    if (r.needsReview > 0) {
      out.add('${r.needsReview} open report${r.needsReview == 1 ? '' : 's'} flagged for human review.');
    }
    if (r.avgResolutionDays != null) {
      out.add('Resolved reports took about ${r.avgResolutionDays!.toStringAsFixed(1)} days on average '
          '(approximate).');
    }
    final busiest = r.byDepartment.entries.where((e) => e.value.open > 0).toList()
      ..sort((a, b) => b.value.open.compareTo(a.value.open));
    if (busiest.isNotEmpty) {
      out.add('Busiest department: ${Departments.nameOf(busiest.first.key)} '
          '(${busiest.first.value.open} open).');
    }
    return out;
  }
}
